"""SEPARATE FEATURES AND TARGET"""

X=df[["age","heart_disease", "hypertension", "avg_glucose_level"]]
Y=df["stroke"]
print("Features(x): ")
print(X.head())
print("target(y): ")
print(Y.head())

"""TRAIN-TEST SPLIT"""

X_train, X_test, Y_train, Y_test = train_test_split(
    X,Y,
    test_size=0.2,
    random_state=42,
    stratify=Y        #store the target
)
print("Trainning records: ", len(X_train))
print("Testing records: ", len(X_test))

"""FEATURE SCALLING PIPELINE"""

model = Pipeline([
    ("scaler", StandardScaler()),
    ("classifier",LogisticRegression())

])

"""TRAIN THE MODEL"""

model.fit(X_train, Y_train)
print("Model training completed.")

"""PREDICT THE TEST DATA"""

Y_pred=model.predict(X_test)
comparison=pd.DataFrame({
    "Actual_Result": Y_test.values,
    "Predicted_stroke": Y_pred
})
print(comparison)

"""CONFUSION MATRIX"""

cm = confusion_matrix(Y_test, Y_pred, labels=[0,1])
print("Rows=Actual, Columns=Predicted")
print(cm)

"""ACCURACY CHECK"""

accuracy=accuracy_score (Y_test,Y_pred)
precision=precision_score(Y_test,Y_pred ,zero_division=0)
recall=recall_score(Y_test,Y_pred,zero_division=0)
f1=f1_score(Y_test,Y_pred,zero_division=0)

print("Accuracy: ",round(accuracy,3))
print("precison: ",round(precision,3))
print("recall: ", round(recall,3))
print("f1-score: ", round(f1,3))

print("\nDetailed classification report: ")
print(classification_report(

    Y_test, Y_pred,
    labels=[0,1],
    target_names=["Fail", "Pass"],
    zero_division=0
))

"""PROBABILITY"""

probabilities= model.predict_proba(X_test)
print("Columns are ordered as classes: ", model.classes_)
print(probabilities)

